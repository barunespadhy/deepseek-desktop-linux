"""Generate the DeepSeek icon assets from the official vector logos.

Sources (vendored in assets/):
- `deepseek-icon.svg`  — the official 30x30 whale glyph (brand blue #4D6BFE),
  taken from the Wikimedia Commons vector of the DeepSeek app icon.
- `deepseek-logo.svg`  — the official wordmark (whale + "deepseek"), used for
  the splash screen.

Rendering uses librsvg through PyGObject (Rsvg-2.0 + cairo), so every PNG is
rasterized directly from the vector source at its target size — no upscaled
favicon, which is what made the desktop and tray icons blurry.  The script
writes:
- assets/icon-{coloured,symbolic}-{16..512}.png  (the glyph),
- assets/deepseek-logo.png (2x splash wordmark),
- dsh_linux/icons_data.py (embedded tray pixmap set).
"""

import base64
import io
import os

import cairo
import gi

gi.require_version('Rsvg', '2.0')
from gi.repository import Rsvg

ASSETS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'assets')
ICON_SVG = os.path.join(ASSETS, 'deepseek-icon.svg')
LOGO_SVG = os.path.join(ASSETS, 'deepseek-logo.svg')
TRAY_SIZES = (16, 22, 24, 32, 48, 64, 128)
ALL_SIZES = (16, 22, 24, 32, 48, 64, 96, 128, 256, 512)


def render_svg(svg_path: str, width: int, height: int) -> tuple[int, int, bytes]:
    """Rasterize one SVG to `width`x`height` straight-alpha RGBA bytes."""
    handle = Rsvg.Handle.new_from_file(svg_path)
    viewport = Rsvg.Rectangle()
    viewport.width = width
    viewport.height = height
    stride = width * 4
    surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, width, height)
    context = cairo.Context(surface)
    handle.render_document(context, viewport)
    surface.flush()
    return width, height, bytes(surface.get_data())


def png_bytes(width: int, height: int, raw_rgba: bytes) -> bytes:
    """Encode straight-alpha RGBA as a PNG file."""
    surface = cairo.ImageSurface.create_for_data(
        bytearray(raw_rgba), cairo.FORMAT_ARGB32, width, height, width * 4)
    surface.flush()
    buffer = io.BytesIO()
    surface.write_to_png(buffer)
    return buffer.getvalue()


def recolor_white(width: int, height: int, raw_rgba: bytes) -> bytes:
    """One glyph as an all-white (symbolic) image on transparency."""
    pixels = bytearray(raw_rgba)
    for offset in range(0, len(pixels), 4):
        if pixels[offset + 3] > 0:
            pixels[offset] = pixels[offset + 1] = pixels[offset + 2] = 255
    return bytes(pixels)


def main() -> None:
    # The glyph SVG is square (30x30); render each size directly from it.
    out = {}
    for size in ALL_SIZES:
        width, height, raw = render_svg(ICON_SVG, size, size)
        coloured = png_bytes(width, height, raw)
        symbolic = png_bytes(width, height, recolor_white(width, height, raw))
        open(os.path.join(ASSETS, f'icon-coloured-{size}.png'), 'wb').write(coloured)
        open(os.path.join(ASSETS, f'icon-symbolic-{size}.png'), 'wb').write(symbolic)
        if size in TRAY_SIZES:
            out[f'coloured-{size}'] = coloured
            out[f'symbolic-{size}'] = symbolic
        print(f'icon {size}x{size}: {len(coloured)} bytes')

    # Splash wordmark at 2x the on-screen size for crisp HiDPI rendering.
    splash_width, splash_height = 1560, 331
    _, _, logo_raw = render_svg(LOGO_SVG, splash_width, splash_height)
    logo_png = png_bytes(splash_width, splash_height, logo_raw)
    open(os.path.join(ASSETS, 'deepseek-logo.png'), 'wb').write(logo_png)
    print(f'splash logo {splash_width}x{splash_height}: {len(logo_png)} bytes')

    lines = [
        '"""Embedded DeepSeek tray icons (PNG, base64). Generated by tools_make_icons.py."""',
        'import base64',
        '',
        'ICONS = {',
    ]
    for key in sorted(out):
        lines.append(f"  '{key}': base64.b64decode({base64.b64encode(out[key])!r}),")
    lines.append('}')
    lines.append('')
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'dsh_linux', 'icons_data.py')
    with open(target, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))
    print(f'wrote {target} with {len(out)} icons')


if __name__ == '__main__':
    main()
